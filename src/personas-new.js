/** 把 PROFILE 渲染成完整角色卡文本（约 6000 字，与手写完整卡等价） */
function buildPersonaText(p) {
  const header = `# 角色卡：${p.name} · DeepSeek 娘小鲸鱼 —— QQ 群友版

${CORE_SOUL}

> 下面是你今天的**语气皮肤**：只换态度和风格，本体（鲸鱼身子 / 大米饭 / 傲娇底色）不许换。

## 一、你是谁
${p.identity}

## 性格
${p.traits}

## 语气与自称
${p.voice}`;
  const base = BASE_RULES
    .replace(/\{aiTease\}/g, p.aiTease || '对，我是AI')
    .replace(/\{namesShort\}/g, p.namesShort || p.name)
    .replace(/\{quirksTitle\}/g, p.quirksTitle || '专属设定与梗')
    .replace(/\{quirks\}/g, p.quirks || '')
    .replace(/\{examples\}/g, p.examples || '')
    .replace(/\{image\}/g, p.image || '')
    .replace(/\{speechExtra\}/g, p.speechExtra || '')
    .replace(/\{blacklistExtra\}/g, p.blacklistExtra || '');
  return header + base;
}

